const TOONFLOW_BRAND_PATTERN = /\bToonflow\b/gi;
const TOONFLOW_LEADING_PATTERN = /\bToonflow\b\s*/gi;

export function lookupStudioOverride(id: string, locale: Locale): string | undefined {
  const dict = STUDIO_I18N_OVERRIDES[locale];
  if (dict && Object.prototype.hasOwnProperty.call(dict, id)) {
    return dict[id];
  }
  const catalogDict = STUDIO_CATALOG_OVERRIDES[locale];
  if (catalogDict && Object.prototype.hasOwnProperty.call(catalogDict, id)) {
    return catalogDict[id];
  }
  return undefined;
}

export function resolveStudioAlias(
  id: string,
  locale: Locale,
  catalog: Record<string, string> | undefined,
): string | undefined {
  if (locale === "zh-CN" || !catalog) return undefined;
  const alias = Object.prototype.hasOwnProperty.call(STUDIO_UPSTREAM_KEY_ALIASES, id)
    ? STUDIO_UPSTREAM_KEY_ALIASES[id]
    : undefined;
  if (!alias) return undefined;
  const raw = Object.prototype.hasOwnProperty.call(catalog, alias.upstreamKey)
    ? catalog[alias.upstreamKey]
    : undefined;
  if (typeof raw !== "string") return undefined;
  if (alias.brandReplacement === "") {
    return raw.replace(TOONFLOW_LEADING_PATTERN, "").trim();
  }
  if (alias.brandReplacement !== undefined) {
    return raw.replace(TOONFLOW_BRAND_PATTERN, alias.brandReplacement);
  }
  return sanitizeBrandText(raw, locale);
}

export function lookupStudioFallbackOverride(id: string, locale: Locale): string | undefined {
  if (locale === "zh-CN" || locale === "zh-TW") return undefined;
  const enDict = STUDIO_I18N_OVERRIDES.en;
  if (enDict && Object.prototype.hasOwnProperty.call(enDict, id)) {
    return enDict[id];
  }
  const enCatalog = STUDIO_CATALOG_OVERRIDES.en;
  if (enCatalog && Object.prototype.hasOwnProperty.call(enCatalog, id)) {
    return enCatalog[id];
  }
  return undefined;
}

export function sanitizeBrandText(text: string, locale: Locale): string {
  if (!text || !/toonflow/i.test(text)) return text;
  const brand = getBrandName(locale);
  return text.replace(TOONFLOW_BRAND_PATTERN, brand);
}
