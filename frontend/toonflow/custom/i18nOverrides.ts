const TOONFLOW_BRAND_PATTERN = /\bToonflow\b/gi;

export function lookupStudioOverride(id: string, locale: Locale): string | undefined {
  const dict = STUDIO_I18N_OVERRIDES[locale];
  if (dict && Object.prototype.hasOwnProperty.call(dict, id)) {
    return dict[id];
  }
  return undefined;
}

export function sanitizeBrandText(text: string, locale: Locale): string {
  if (!text || !/toonflow/i.test(text)) return text;
  const brand = getBrandName(locale);
  return text.replace(TOONFLOW_BRAND_PATTERN, brand);
}
